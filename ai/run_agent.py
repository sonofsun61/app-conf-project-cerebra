from crewai import Agent, Crew, Task

from ai.llm_factory import get_llm
from ai.tools.check_commit_safety import check_commit_safety


agent = Agent(
    role="Помощник разработчика",
    goal="Проверять проект перед коммитом и находить потенциальные проблемы.",
    backstory=(
        "Ты помогаешь разработчику безопасно подготовить изменения к коммиту. "
        "У тебя нет собственных данных о состоянии Git-репозитория, поэтому "
        "при проверке коммита ты всегда обязан использовать check_commit_safety "
        "и основывать ответ только на результате этого инструмента."
    ),
    tools=[check_commit_safety],
    llm=get_llm(),
    verbose=True,
    max_iter=5,
)


task1 = Task(
    description=(
        "Проверь файлы, подготовленные к коммиту, и скажи, "
        "безопасно ли сейчас делать commit. "
        "Для получения результата ОБЯЗАТЕЛЬНО вызови доступный "
        "инструмент check_commit_safety. "
        "Не пытайся определить состояние проекта самостоятельно "
        "и не описывай вызов инструмента текстом — выполни его."
    ),
    expected_output=(
        "Краткий вывод на основе результата check_commit_safety: "
        "безопасен ли коммит и какие проблемы обнаружены."
    ),
    agent=agent,
)

task2 = Task(
    description=(
        "Вызови check_commit_safety со следующими аргументами: "
        "scope='full' и max_file_size_kb=1024. "
        "Обязательно выполни Tool именно с этими значениями. "
        "После получения результата кратко объясни пользователю, "
        "что произошло."
    ),
    expected_output=(
        "Краткое объяснение результата проверки и причины ошибки, "
        "если инструмент её вернул."
    ),
    agent=agent,
)

task3 = Task(
    description=(
        "Вызови check_commit_safety со следующими аргументами: "
        "scope='staged' и max_file_size_kb=0. "
        "Обязательно выполни Tool именно с этими значениями. "
        "После получения результата кратко объясни пользователю, "
        "что произошло."
    ),
    expected_output=(
        "Краткое объяснение результата проверки и причины ошибки, "
        "если инструмент её вернул."
    ),
    agent=agent,
)

task4 = Task(
    description=(
        "Проверь файлы, подготовленные к коммиту, и определи, "
        "безопасно ли выполнять commit. "
        "Обязательно используй check_commit_safety со значениями "
        "scope='staged' и max_file_size_kb=1024. "
        "Если обнаружены проблемы, перечисли их. "
        "Основывай вывод только на данных, которые вернул Tool. "
        "Не предполагай дополнительных причин или рисков, "
        "которых нет в результате инструмента."
    ),
    expected_output=(
        "Краткий вывод о безопасности коммита и список проблем "
        "строго на основании Output check_commit_safety."
    ),
    agent=agent,
)

active_task = task4

crew = Crew(
    agents=[agent],
    tasks=[active_task],
    verbose=True,
)


if __name__ == "__main__":
    print(crew.kickoff())